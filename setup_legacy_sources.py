"""Source list of the frozen legacy extension (csrc_legacy/).

Kept in its own module so that setup.py's current-side lists stay a verbatim copy of
upstream's, and a sync is a straight replacement of csrc/ plus upstream's own setup.py lists.

The tree is generated by tools/make_legacy_tree.py from the fork's `sgl` branch; see
csrc_legacy/README.md for what it is and where it came from.
"""

from pathlib import Path

LEGACY_DIR = Path("csrc_legacy")

# `legacy::` kernels are instantiated for Hopper as well as Blackwell; the current side is
# SM100-only, so each extension compiles fewer architectures than the old combined build.
LEGACY_CUDA_ARCHS = ["sm_90a", "sm_100a", "sm_103a"]

LEGACY_API_SOURCES = [
    # The op schemas; each implementation binds itself next to its definition.
    "csrc_legacy/ops.cpp",
    "csrc_legacy/sched_meta.cpp",
    "csrc_legacy/api/sparse_prefill.cpp",
    "csrc_legacy/api/sparse_decode.cpp",
    "csrc_legacy/api/dense_decode.cpp",
    "csrc_legacy/api/fused_norm_rope_attn_rope_cast_fwd.cpp",
    # The fork's own SM90 dense fp8 attention, which upstream never had
    "csrc_legacy/extension/sm90/dense_fp8/dense_fp8_python_api.cpp",
]


# The SM100 dense prefill (CUTLASS FMHA) is byte-identical to the current side's copy, and the
# current side already registers `dense_prefill_fwd`/`_bwd`. Its sources stay in the tree -- the
# frozen snapshot is complete -- but compiling the heaviest translation units in the build twice
# for an identical result is not worth it.
NOT_BUILT = ("csrc_legacy/kernels/sm100/prefill/dense/",)


def legacy_kernel_sources():
    """Every .cu under csrc_legacy/, so the list cannot drift from the generated tree."""
    return sorted(str(p) for p in LEGACY_DIR.rglob("*.cu")
                  if not str(p).startswith(NOT_BUILT))


def legacy_sources():
    return LEGACY_API_SOURCES + legacy_kernel_sources()
